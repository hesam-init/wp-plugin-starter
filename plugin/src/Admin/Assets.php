<?php
/**
 * Enqueues the React admin app, its translations and its boot data.
 *
 * @package WpPluginStarter
 */

declare( strict_types=1 );

namespace WpPluginStarter\Admin;

use WpPluginStarter\Plugin;
use WpPluginStarter\Rest\AbstractController;
use WpPluginStarter\Support\Vite;

defined( 'ABSPATH' ) || exit;

/**
 * Admin assets.
 */
final class Assets {

	public const HANDLE    = 'wp-plugin-starter-admin';
	public const JS_GLOBAL = 'wpPluginStarter';

	/**
	 * WordPress packages the app uses as globals instead of bundling them
	 * (see admin-client/src/wp-globals). Keep in sync with vite.config.ts.
	 */
	private const WP_DEPENDENCIES = array( 'wp-i18n', 'wp-api-fetch' );

	/**
	 * Constructor.
	 *
	 * @param Vite $vite Vite bridge.
	 */
	public function __construct( private Vite $vite ) {}

	/**
	 * Enqueue the app. Returns false if the build is missing.
	 */
	public function enqueue(): bool {
		if ( ! $this->vite->enqueue( self::HANDLE, self::WP_DEPENDENCIES ) ) {
			return false;
		}

		$this->load_translations();

		// Classic inline script printed *before* the module, so config is ready on boot.
		wp_add_inline_script(
			self::HANDLE,
			sprintf( 'window.%s = %s;', self::JS_GLOBAL, wp_json_encode( $this->config() ) ),
			'before'
		);

		return true;
	}

	/**
	 * Feed translations into wp.i18n before the app runs.
	 *
	 * 1. Our strings: languages/{domain}-{locale}-{handle}.json, generated by
	 *    `make i18n` (WordPress looks for this handle-based name first, so it
	 *    survives Vite's hashed file names).
	 * 2. Strings of the bundled @wordpress/components (Close, Search, …) live in
	 *    core's "default" domain; borrow them from the registered wp-components
	 *    script without loading that script.
	 */
	private function load_translations(): void {
		wp_set_script_translations( self::HANDLE, Plugin::TEXT_DOMAIN, WP_PLUGIN_STARTER_DIR . 'languages' );

		$core = wp_scripts()->print_translations( 'wp-components', false );
		if ( is_string( $core ) && '' !== $core ) {
			wp_add_inline_script( self::HANDLE, $core, 'before' );
		}
	}

	/**
	 * Data the React app validates with zod (see admin-client/src/lib/config.ts).
	 * REST root + nonce are not needed: WordPress configures wp.apiFetch.
	 *
	 * @return array<string, mixed>
	 */
	private function config(): array {
		$user = wp_get_current_user();

		return array(
			'name'          => Plugin::NAME,
			'version'       => WP_PLUGIN_STARTER_VERSION,
			'restNamespace' => AbstractController::API_NAMESPACE,
			'adminUrl'      => admin_url(),
			'pluginUrl'     => WP_PLUGIN_STARTER_URL,
			'locale'        => determine_locale(),
			'user'          => array(
				'id'          => $user->ID,
				'displayName' => $user->display_name,
			),
		);
	}
}
